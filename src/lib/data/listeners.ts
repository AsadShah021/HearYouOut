export const listenerMap = Object.fromEntries(
  listeners.map((listener) => [listener.id, listener]),
) as Record<string, Listener>;

export const featuredListeners = listeners.filter((listener) => listener.featured);

export function getListener(id: string) {
  return listenerMap[id];
}

export function getListenerBySlug(slug: string) {
  return listeners.find((listener) => listener.slug === slug);
}

